#include <iostream>     // Библиотека для ввода и вывода данных
#include <vector>       // Контейнер vector для хранения массива
#include <cmath>        // Математические операции
#include <omp.h>        // Библиотека OpenMP для параллельных вычислений

int main() {
    // Размер большого массива данных
    // Большой размер нужен для наглядной демонстрации ускорения
    const int N = 50'000'000;

    // Создание массива из N элементов, инициализированных значением 1.0
    std::vector<double> data(N, 1.0);

    // ============================================================
    // ПОСЛЕДОВАТЕЛЬНАЯ ВЕРСИЯ ПРОГРАММЫ
    // Используется для определения базового времени выполнения
    // ============================================================

    // Фиксация времени начала последовательных вычислений
    double t_seq_start = omp_get_wtime();

    // Переменная для хранения суммы элементов массива
    double sum_seq = 0.0;

    // Последовательное вычисление суммы
    for (int i = 0; i < N; i++)
        sum_seq += data[i];

    // Вычисление среднего значения
    double mean_seq = sum_seq / N;

    // Переменная для хранения дисперсии
    double var_seq = 0.0;

    // Последовательное вычисление дисперсии
    for (int i = 0; i < N; i++)
        var_seq += (data[i] - mean_seq) * (data[i] - mean_seq);

    // Нормировка дисперсии
    var_seq /= N;

    // Фиксация времени окончания последовательных вычислений
    double t_seq_end = omp_get_wtime();

    // Общее время выполнения последовательной версии
    double T_seq = t_seq_end - t_seq_start;

    // Вывод времени последовательного выполнения
    std::cout << "Последовательное время: " << T_seq << " сек\n\n";

    // ============================================================
    // ПАРАЛЛЕЛЬНАЯ ВЕРСИЯ С ИСПОЛЬЗОВАНИЕМ OPENMP
    // ============================================================

    // Перебор количества потоков OpenMP
    // Это позволяет проанализировать масштабируемость программы
    for (int threads = 1; threads <= 8; threads *= 2) {

        // Установка количества потоков OpenMP
        omp_set_num_threads(threads);

        // Фиксация времени начала параллельных вычислений
        double t_par_start = omp_get_wtime();

        // Переменная для суммы (используется редукция)
        double sum = 0.0;

        // Параллельный цикл вычисления суммы
        // reduction(+:sum) обеспечивает корректное суммирование
#pragma omp parallel for reduction(+:sum)
        for (int i = 0; i < N; i++)
            sum += data[i];

        // Вычисление среднего значения
        // Эта операция является последовательной
        double mean = sum / N;

        // Переменная для хранения дисперсии
        double var = 0.0;

        // Параллельный цикл вычисления дисперсии
#pragma omp parallel for reduction(+:var)
        for (int i = 0; i < N; i++)
            var += (data[i] - mean) * (data[i] - mean);

        // Нормировка дисперсии
        var /= N;

        // Фиксация времени окончания параллельных вычислений
        double t_par_end = omp_get_wtime();

        // Общее время выполнения параллельной версии
        double T_par = t_par_end - t_par_start;

        // Вычисление ускорения относительно последовательной версии
        double speedup = T_seq / T_par;

        // Вывод результатов
        std::cout << "Потоки: " << threads
            << " | Время: " << T_par << " сек"
            << " | Ускорение: " << speedup << std::endl;
    }

    return 0;
}